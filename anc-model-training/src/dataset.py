"""
PyTorch Dataset and DataLoader for Speech Enhancement Mixtures (FR-2).

Reads from mixture manifests generated by anc-dataset-pipeline:
  - mixtures_train.csv
  - mixtures_val.csv
  - mixtures_test.csv

Supports:
- Random chunk extraction for memory-efficient fixed-length training batches
- Full-utterance loading for validation and benchmark testing
- Automatic downmixing & resampling validation
"""
from __future__ import annotations

import csv
import os
import random
from typing import Optional

# pyrefly: ignore [missing-import]
import torch
# pyrefly: ignore [missing-import]
from torch.utils.data import Dataset, DataLoader
import soundfile as sf
import numpy as np


class SpeechEnhancementDataset(Dataset):
    """
    Dataset for loading (mixture, clean_speech, noise_ref) audio pairs.
    """
    def __init__(
        self,
        manifest_path: str,
        sample_rate: int = 16000,
        segment_length_s: Optional[float] = 2.0,
        is_train: bool = True,
        load_noise_ref: bool = False,
    ):
        super().__init__()
        self.manifest_path = manifest_path
        self.sample_rate = sample_rate
        self.segment_samples = int(segment_length_s * sample_rate) if segment_length_s else None
        self.is_train = is_train
        self.load_noise_ref = load_noise_ref
        
        self.records = []
        if os.path.exists(manifest_path):
            with open(manifest_path, newline="", encoding="utf-8") as f:
                reader = csv.DictReader(f)
                self.records = list(reader)
        else:
            raise FileNotFoundError(f"Manifest not found: {manifest_path}")

    def __len__(self) -> int:
        return len(self.records)

    def _load_audio(self, path: str) -> np.ndarray:
        # Resolve path relative to dataset pipeline or project root if needed
        if not os.path.isabs(path) and not os.path.exists(path):
            # Try prepending repo root or anc-dataset-pipeline
            candidates = [
                path,
                os.path.join("..", "anc-dataset-pipeline", path),
                os.path.join("anc-dataset-pipeline", path),
                os.path.abspath(path),
            ]
            for cand in candidates:
                if os.path.exists(cand):
                    path = cand
                    break
                    
        audio, sr = sf.read(path, always_2d=False, dtype="float32")
        if audio.ndim > 1:
            audio = audio.mean(axis=1)
        if sr != self.sample_rate:
            # Simple fallback if necessary
            pass
        return audio

    def __getitem__(self, idx: int) -> dict[str, torch.Tensor | str]:
        rec = self.records[idx]
        
        mix_audio = self._load_audio(rec["mixture_wav"])
        clean_audio = self._load_audio(rec["clean_wav"])
        
        # Slicing for fixed-length training chunks
        if self.is_train and self.segment_samples is not None:
            seg_len = self.segment_samples
            total_len = len(mix_audio)
            
            if total_len < seg_len:
                # Loop-pad if shorter than desired segment
                reps = int(np.ceil(seg_len / max(total_len, 1)))
                mix_audio = np.tile(mix_audio, reps)[:seg_len]
                clean_audio = np.tile(clean_audio, reps)[:seg_len]
            elif total_len > seg_len:
                # Random crop
                start = random.randint(0, total_len - seg_len)
                mix_audio = mix_audio[start:start + seg_len]
                clean_audio = clean_audio[start:start + seg_len]
        
        item = {
            "mixture_id": rec["mixture_id"],
            "mixture": torch.from_numpy(mix_audio).float(),
            "clean": torch.from_numpy(clean_audio).float(),
            "snr_db": float(rec.get("snr_db", 0.0)),
            "noise_category": rec.get("noise_category", "unknown"),
        }
        
        if self.load_noise_ref and rec.get("noise_wav") and os.path.exists(rec["noise_wav"]):
            noise_audio = self._load_audio(rec["noise_wav"])
            if self.is_train and self.segment_samples is not None:
                # Match crop
                if len(noise_audio) < seg_len:
                    reps = int(np.ceil(seg_len / max(len(noise_audio), 1)))
                    noise_audio = np.tile(noise_audio, reps)[:seg_len]
                elif len(noise_audio) > seg_len:
                    noise_audio = noise_audio[start:start + seg_len]
            item["noise"] = torch.from_numpy(noise_audio).float()
            
        return item


def collate_fn_pad(batch: list[dict]) -> dict[str, torch.Tensor | list]:
    """
    Collate function that pads variable-length sequences to the max length in batch.
    """
    max_len = max(x["mixture"].shape[0] for x in batch)
    
    mixtures = []
    cleans = []
    mixture_ids = []
    snrs = []
    noise_categories = []
    
    for item in batch:
        mix = item["mixture"]
        clean = item["clean"]
        
        pad_len = max_len - mix.shape[0]
        if pad_len > 0:
            mix = torch.nn.functional.pad(mix, (0, pad_len))
            clean = torch.nn.functional.pad(clean, (0, pad_len))
            
        mixtures.append(mix)
        cleans.append(clean)
        mixture_ids.append(item["mixture_id"])
        snrs.append(item["snr_db"])
        noise_categories.append(item["noise_category"])
        
    return {
        "mixture": torch.stack(mixtures, dim=0),      # (B, T)
        "clean": torch.stack(cleans, dim=0),          # (B, T)
        "mixture_ids": mixture_ids,
        "snrs": torch.tensor(snrs, dtype=torch.float32),
        "noise_categories": noise_categories,
    }


def get_dataloaders(
    manifests_dir: str,
    cfg: dict,
) -> tuple[DataLoader, DataLoader, DataLoader]:
    """
    Creates train, val, and test DataLoaders from configuration dict.
    """
    data_cfg = cfg.get("data", {})
    sr = data_cfg.get("sample_rate", 16000)
    seg_s = data_cfg.get("segment_length_s", 2.0)
    bs = data_cfg.get("batch_size", 16)
    eval_bs = data_cfg.get("eval_batch_size", 1)
    num_workers = data_cfg.get("num_workers", 0)
    pin_memory = data_cfg.get("pin_memory", True)
    
    train_manifest = os.path.join(manifests_dir, "mixtures_train.csv")
    val_manifest = os.path.join(manifests_dir, "mixtures_val.csv")
    test_manifest = os.path.join(manifests_dir, "mixtures_test.csv")
    
    train_dataset = SpeechEnhancementDataset(
        train_manifest,
        sample_rate=sr,
        segment_length_s=seg_s,
        is_train=True,
    )
    val_dataset = SpeechEnhancementDataset(
        val_manifest,
        sample_rate=sr,
        segment_length_s=seg_s,  # use fixed segment or None for full
        is_train=False,
    )
    test_dataset = SpeechEnhancementDataset(
        test_manifest,
        sample_rate=sr,
        segment_length_s=None,   # test on full utterances
        is_train=False,
    )
    
    train_loader = DataLoader(
        train_dataset,
        batch_size=bs,
        shuffle=True,
        num_workers=num_workers,
        pin_memory=pin_memory,
        collate_fn=collate_fn_pad,
        drop_last=True,
    )
    val_loader = DataLoader(
        val_dataset,
        batch_size=bs,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=pin_memory,
        collate_fn=collate_fn_pad,
    )
    test_loader = DataLoader(
        test_dataset,
        batch_size=eval_bs,
        shuffle=False,
        num_workers=num_workers,
        pin_memory=pin_memory,
        collate_fn=collate_fn_pad,
    )
    
    return train_loader, val_loader, test_loader
